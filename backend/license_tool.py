#!/usr/bin/env python3
"""License tool for the SUG/SRC e-Voting System.

VENDOR commands (need the private key, which must NEVER be committed or shipped):
    python backend/license_tool.py keygen --out C:\\secure\\license_private.pem
    python backend/license_tool.py issue  --key C:\\secure\\license_private.pem --licensee "Auchi Polytechnic" --days 31
    python backend/license_tool.py unlock --key C:\\secure\\license_private.pem --lock-id 1A2B3C4D

CUSTOMER commands (need only the public key that ships with the application):
    python backend/license_tool.py status            (also what double-clicking license.bat runs)
    python backend/license_tool.py apply-unlock CODE (lifts a hard lock; the web screen can do the same)
"""
import argparse
import base64
import os
import sys
import uuid
from datetime import date, datetime, timedelta, timezone
from pathlib import Path

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from core import licensing  # noqa: E402

BACKEND_DIR = Path(__file__).resolve().parent
PUBLIC_PY = BACKEND_DIR / "core" / "license_public.py"
DEFAULT_LICENSE = BACKEND_DIR.parent / "license.bat"

TEMPLATE = """@echo off
REM ======================================================================
REM  SUG/SRC e-Voting System - LICENSE FILE
REM  Do not edit, rename, move or delete this file.
REM  Any change locks the application until a valid license is restored.
REM ======================================================================
REM PRODUCT: {product}
REM LICENSE-ID: {license_id}
REM LICENSEE: {licensee}
REM ISSUED: {issued}
REM EXPIRES: {expires}
REM SIGNATURE: {signature}
set "PY=python"
if exist "%~dp0backend\\.venv\\Scripts\\python.exe" set "PY=%~dp0backend\\.venv\\Scripts\\python.exe"
"%PY%" "%~dp0backend\\license_tool.py" status
pause
"""


def load_private(path: str) -> Ed25519PrivateKey:
    key = serialization.load_pem_private_key(Path(path).read_bytes(), password=None)
    if not isinstance(key, Ed25519PrivateKey):
        raise SystemExit("That is not an Ed25519 private key.")
    return key


def keygen(out: str, public_py: Path = PUBLIC_PY) -> str:
    """Create the signing key. Returns the public key (base64). Refuses to overwrite an existing private key."""
    private = Ed25519PrivateKey.generate()
    pem = private.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8, serialization.NoEncryption())
    fd = os.open(out, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)   # fails if the file already exists
    with os.fdopen(fd, "wb") as f:
        f.write(pem)
    public_b64 = base64.b64encode(private.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)).decode()
    public_py.write_text('"""Public half of the license-signing key. It is safe to commit this file.\n\n'
                         'Generated by:  python backend/license_tool.py keygen\n'
                         'Empty means no key has been created yet, so the application stays locked.\n"""\n'
                         f'PUBLIC_KEY_B64 = "{public_b64}"\n', encoding="utf-8")
    return public_b64


def issue(key_path: str, licensee: str, expires: date, out: Path = DEFAULT_LICENSE, today: date | None = None) -> Path:
    """Write a signed license.bat. The file uses Windows (CRLF) line endings."""
    licensee = " ".join(licensee.split())[:120]
    if not licensee:
        raise SystemExit("--licensee must not be empty.")
    today = today or datetime.now(timezone.utc).date()
    if expires < today:
        raise SystemExit("The expiry date is in the past.")
    fields = dict(product=licensing.PRODUCT, license_id=uuid.uuid4().hex[:12].upper(), licensee=licensee,
                  issued=today.isoformat(), expires=expires.isoformat())
    unsigned = TEMPLATE.format(signature="", **fields)
    signature = base64.b64encode(load_private(key_path).sign(licensing.canonical(unsigned))).decode()
    text = TEMPLATE.format(signature=signature, **fields).replace("\n", "\r\n")
    out.write_bytes(text.encode("utf-8"))
    return out


def unlock_code(key_path: str, lock_id: str) -> str:
    return base64.urlsafe_b64encode(load_private(key_path).sign(licensing.unlock_message(lock_id.strip().upper()))).decode().rstrip("=")


def status(path: Path | None = None) -> int:
    path = path or licensing.find_file()
    if path is None or not Path(path).is_file():
        print("License: NOT FOUND (license.bat is missing).")
        return 1
    try:
        info = licensing.parse_and_verify(Path(path).read_text(encoding="utf-8-sig"))
    except licensing.LicenseProblem as e:
        print(e.message)
        return 1
    left = (info.expires - datetime.now(timezone.utc).date()).days
    if left < 0:
        print(f"License: EXPIRED on {info.expires} ({-left} days ago)")
        return 1
    print(f"License: VALID\n  Licensee : {info.licensee}\n  License  : {info.license_id}\n"
          f"  Issued   : {info.issued}\n  Expires  : {info.expires} ({left} days left)")
    return 0


def apply_unlock(token: str) -> int:
    from core.db import SessionLocal, init_db
    init_db()
    db = SessionLocal()
    try:
        result = licensing.apply_unlock(db, token)
        print("Unlocked." if result.valid else f"Unlock accepted, but: {result.message}")
        return 0
    except Exception as exc:
        print(getattr(exc, "message", str(exc)))
        return 1
    finally:
        db.close()


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    k = sub.add_parser("keygen", help="vendor: create the signing key pair")
    k.add_argument("--out", default="license_private.pem", help="where to save the PRIVATE key (keep it out of the project folder)")
    i = sub.add_parser("issue", help="vendor: write a signed license.bat in the project root")
    i.add_argument("--key", required=True)
    i.add_argument("--licensee", required=True)
    g = i.add_mutually_exclusive_group()
    g.add_argument("--days", type=int, default=31, help="valid for this many days from today (default 31)")
    g.add_argument("--expires", help="last valid day, YYYY-MM-DD")
    i.add_argument("--out", default=str(DEFAULT_LICENSE))
    u = sub.add_parser("unlock", help="vendor: create an unlock code for a hard lock")
    u.add_argument("--key", required=True)
    u.add_argument("--lock-id", required=True)
    sub.add_parser("status", help="show the state of license.bat")
    a = sub.add_parser("apply-unlock", help="customer: apply a vendor unlock code")
    a.add_argument("token")
    args = ap.parse_args(argv)

    if args.cmd == "keygen":
        pub = keygen(args.out)
        print(f"Private key saved to: {args.out}\nPublic key written to: {PUBLIC_PY}\n  {pub}\n\n"
              "KEEP THE PRIVATE KEY SAFE AND OFFLINE. Anyone who has it can issue licenses; if you lose it you cannot issue renewals.\n"
              "Do not commit it to Git. Commit core/license_public.py. Licenses issued with an older key stop working.")
        return 0
    if args.cmd == "issue":
        expires = date.fromisoformat(args.expires) if args.expires else datetime.now(timezone.utc).date() + timedelta(days=args.days)
        path = issue(args.key, args.licensee, expires, Path(args.out))
        print(f"License written to {path}\nExpires: {expires} (valid through the end of that day, UTC)")
        return 0
    if args.cmd == "unlock":
        print(unlock_code(args.key, args.lock_id))
        return 0
    if args.cmd == "status":
        return status()
    return apply_unlock(args.token)


if __name__ == "__main__":
    sys.exit(main())
